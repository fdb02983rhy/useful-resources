import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const resourcesDir = path.resolve(scriptDir, "../../resources/2026");
const outputPath = path.resolve(scriptDir, "../app/resources.ts");

function parseFrontmatter(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error("Missing frontmatter");

  return Object.fromEntries(
    match[1].split("\n").map((line) => {
      const separator = line.indexOf(":");
      const key = line.slice(0, separator).trim();
      const value = line
        .slice(separator + 1)
        .trim()
        .replace(/^(["'])(.*)\1$/, "$2");
      return [key, value];
    }),
  );
}

function section(markdown, heading, level = 2) {
  const prefix = "#".repeat(level);
  const startMarker = `${prefix} ${heading}`;
  const start = markdown.indexOf(startMarker);
  if (start === -1) return "";

  const contentStart = start + startMarker.length;
  const nextHeading = new RegExp(`\\n#{1,${level}} `, "g");
  nextHeading.lastIndex = contentStart;
  const match = nextHeading.exec(markdown);
  return markdown.slice(contentStart, match?.index ?? markdown.length).trim();
}

function cleanMarkdown(value) {
  return value
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function bulletList(value) {
  const bullets = [];

  for (const line of value.split("\n")) {
    if (/^-\s+/.test(line)) {
      bullets.push(line.replace(/^-\s+/, ""));
    } else if (bullets.length && line.trim()) {
      bullets[bullets.length - 1] += ` ${line.trim()}`;
    }
  }

  return bullets.map(cleanMarkdown);
}

function parseTopics(value) {
  return value
    .replace(/^\[/, "")
    .replace(/\]$/, "")
    .split(",")
    .map((topic) => topic.trim())
    .filter(Boolean);
}

const files = (await readdir(resourcesDir))
  .filter((file) => file.endsWith(".md"))
  .sort();

const resources = await Promise.all(
  files.map(async (file) => {
    const markdown = await readFile(path.join(resourcesDir, file), "utf8");
    const meta = parseFrontmatter(markdown);

    return {
      id: meta.id,
      title: meta.title,
      kind: meta.kind,
      sourceUrl: meta.source_url,
      added: meta.added,
      status: meta.status,
      topics: parseTopics(meta.topics),
      summary: cleanMarkdown(section(markdown, "Summary")),
      whySaved: bulletList(section(markdown, "Why this was saved")),
      highlights: bulletList(section(markdown, "Source claims", 3)).slice(0, 4),
    };
  }),
);

const output = `// Generated by npm run sync. Do not edit by hand.\n\nexport type Resource = {\n  id: string;\n  title: string;\n  kind: string;\n  sourceUrl: string;\n  added: string;\n  status: string;\n  topics: string[];\n  summary: string;\n  whySaved: string[];\n  highlights: string[];\n};\n\nexport const resources: Resource[] = ${JSON.stringify(resources, null, 2)};\n`;

await writeFile(outputPath, output, "utf8");
console.log(`Synced ${resources.length} resources.`);
